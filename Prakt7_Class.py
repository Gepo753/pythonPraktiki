class GroupISP3X:
    # Атрибут класса (по умолчанию). Принадлежит самому классу, как в лекции.
    group_name = "ИСП-3Х"
    students_count = 25  # Количество человек в группе по умолчанию

    # Конструктор класса (init), вызывается автоматически при создании объекта
    def __init__(self, student_name, debt_count):
        # Дополнительные атрибуты экземпляра (свойства)
        self.student_name = student_name
        self.debt_count = debt_count

    # Метод для изменения целочисленных показателей на +1 или -1
    def change_debts(self, action):
        if action == '+':
            self.debt_count += 1
            print(f"[-] Добавлен долг. Текущее количество: {self.debt_count}")
        elif action == '-':
            self.debt_count -= 1
            print(f"[+] Долг сдан. Текущее количество: {self.debt_count}")

    # Метод для вывода всей информации (как требуется в задании)
    def display_info(self):
        print("\n--- Информация о группе и студенте ---")
        print(f"Группа: {self.group_name}")
        print(f"Всего человек в группе: {self.students_count}")
        print(f"Имя будущего отчисленца: {self.student_name}")
        print(f"Количество долгов: {self.debt_count}")
        print("--------------------------------------\n")


# === Основной исполняемый код (main.py) ===

print("Добро пожаловать в систему учета долгов!")

# Ввод данных с обработкой ошибок (из Лекции 2 и 3)
name = input("Введите имя будущего отчисленца: ")

while True:
    try:
        # Ввод количества долгов (с проверкой на корректность, как в Лекции 3)
        debts = int(input("Введите начальное количество долгов: "))
        break  # Выход из цикла, если введено число
    except ValueError:
        print("Ошибка! Введите корректное целое число.")

# Создаем экземпляр класса (объект)
student = GroupISP3X(name, debts)

# Выводим первоначальную информацию
student.display_info()

# Бесконечный цикл для управления долгами через консоль
while True:
    print("Введите '+' чтобы добавить долг, '-' чтобы сдать долг, 'q' для выхода.")
    action = input("Ваше действие: ")

    if action == 'q':
        print("Программа завершена. До свидания!")
        break
    elif action in ['+', '-']:
        # Вызов метода, изменяющего показатель
        student.change_debts(action)
        # Вывод обновленной информации
        student.display_info()
    else:
        print("Неизвестная команда. Пожалуйста, используйте '+', '-' или 'q'.")